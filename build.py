def live(t, key):
    """The launch-day variant of a string (`<key>_live`) once the app is live, else the pre-launch one."""
    return t.get(key + "_live", t[key]) if APP_STORE_LIVE else t[key]

def esc(s):
    return html.escape(str(s), quote=True)

def num(n, lang):
    """1240 → '1.240' (tr) / '1,240' (en)."""
    return f"{n:,}".replace(",", "." if lang == "tr" else ",")

# ------------------------------------------------------------------------------------------- colour
def _lum(hex_):
    def ch(c):
        c = int(hex_[c:c + 2], 16) / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * ch(1) + 0.7152 * ch(3) + 0.0722 * ch(5)

def contrast(a, b):
    la, lb = sorted((_lum(a), _lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)

def mix(a, b, t):
    pa = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    pb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02X}" for x, y in zip(pa, pb))

NAVY, CREAM, CREAM100, WHITE = "#1E2A4A", "#FFF8EC", "#FBEEDA", "#FFFFFF"

def accent_set(acc):
    """The age accent, its deep tone and a soft tint. The deep tone carries white text (tags, buttons) and is itself text
    on cream and on the soft tint (eyebrows, rule labels), so it darkens towards navy until all of those reach 4.5:1."""
    soft = mix(acc, CREAM, 0.78)
    deep, t = acc, 0.0
    while min(contrast(deep, WHITE), contrast(deep, CREAM), contrast(deep, CREAM100), contrast(deep, soft)) < 4.6 and t < 0.9:
        t += 0.04
        deep = mix(acc, NAVY, t)
    return acc, deep, soft

def accents_css():
    rules = []
    for item in GAME["ages"] + GAME["realms"]:
        acc, deep, soft = accent_set(item["accent"])
        rules.append(f".acc-{item['id']} {{ --acc: {acc}; --acc-deep: {deep}; --acc-soft: {soft}; }}")
    return "/* Generated by build.py from data/game.json: one accent set per age and realm. */\n" + "\n".join(rules) + "\n"

