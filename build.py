def build():
    written = []
    def write(rel, text):
        p = ROOT / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        written.append(rel)
    write("assets/accents.css", accents_css())
    write("index.html", landing("tr"))
    write("en/index.html", landing("en"))
    for d in DOCS:
        write(f"{d[0]}/index.html", document(*d))
    write("404.html", not_found())
    # Every relative link must resolve to a built file or an asset.
    missing = []
    for rel in written:
        if not rel.endswith(".html"):
            continue
        page = (ROOT / rel).read_text()
        for href in re.findall(r'(?:href|src)="([^"#:]+?)"', page):
            if href.startswith("/kilkule-app/"):
                href = href[len("/kilkule-app/"):] or "index.html"
                target = ROOT / href
            else:
                target = (ROOT / rel).parent / href
            if href.endswith("/") or target.is_dir():
                target = target / "index.html"
            if not target.resolve().exists():
                missing.append((rel, href))
        for frag in re.findall(r'href="#([^"]+)"', page):
            if f'id="{frag}"' not in page:
                missing.append((rel, "#" + frag))
    print("built:", ", ".join(written))
    if missing:
        raise SystemExit(f"broken links: {missing}")
    print("links ok")

if __name__ == "__main__":
    build()
