def document(out_dir, lang, src, title, desc):
    t = S[lang]
    r = "../" * (out_dir.count("/") + 1)
    body = (SRC / src).read_text().replace("{{CONTACT}}", CONTACT).replace("{{UPDATED}}", UPDATED[lang]).replace("{{R}}", r)
    home = r + ("en/" if lang == "en" else "")
